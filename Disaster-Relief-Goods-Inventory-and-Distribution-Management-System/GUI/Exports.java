package GUI;

import GUI.Theme.Tone;
import LIB.PdfWriter;
import LIB.ReportService;
import LIB.ReportTable;
import LIB.Time;
import LIB.XlsxWriter;
import java.awt.Component;
import java.awt.Desktop;
import java.io.File;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import javax.swing.JFileChooser;
import javax.swing.SwingUtilities;
import javax.swing.filechooser.FileNameExtensionFilter;

/** Saves reports and receipts as Excel or PDF files and tells the user where they went. */
final class Exports {
    private Exports() {
    }

    static List<String> meta(String... filters) {
        List<String> lines = new ArrayList<>();
        lines.add("Generated by " + Session.user.getName() + " · " + Time.longStamp(Time.now()));
        for (String filter : filters) {
            if (filter != null && !filter.isEmpty()) {
                lines.add(filter);
            }
        }
        return lines;
    }

    static String workspaceLine() {
        return "Barangay " + Session.workspace.getName() + " · " + Session.workspace.getMunicipality() + ", "
                + Session.workspace.getProvince();
    }

    /** Builds a report in the background, asks where to save it, then writes the file. */
    static void report(Component parent, String group, ReportService.Params params, boolean excel, String... filters) {
        Task.run(() -> new ReportService().build(group, params), table -> save(parent, table, excel, filters),
                error -> Dialogs.error(parent, error));
    }

    static void save(Component parent, ReportTable table, boolean excel, String... filters) {
        String extension = excel ? "xlsx" : "pdf";
        File file = choose(parent, table.title + " " + Time.today(), extension);
        if (file == null) {
            return;
        }
        Task.run(() -> {
            Path path = file.toPath();
            if (excel) {
                XlsxWriter.writeReport(path, workspaceLine(), meta(filters), table);
            } else {
                PdfWriter.forReport(workspaceLine(), meta(filters), table).save(path);
            }
            return file;
        }, saved -> done(parent, saved), error -> Dialogs.error(parent, error));
    }

    static File choose(Component parent, String suggestedName, String extension) {
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Save " + extension.toUpperCase());
        chooser.setFileFilter(new FileNameExtensionFilter(extension.toUpperCase() + " files", extension));
        chooser.setSelectedFile(new File(suggestedName.replaceAll("[\\\\/:*?\"<>|]", "-") + "." + extension));
        if (chooser.showSaveDialog(SwingUtilities.getWindowAncestor(parent)) != JFileChooser.APPROVE_OPTION) {
            return null;
        }
        File file = chooser.getSelectedFile();
        return file.getName().toLowerCase().endsWith("." + extension) ? file : new File(file.getPath() + "." + extension);
    }

    static void done(Component parent, File file) {
        boolean open = Dialogs.confirm(parent, "File saved", file.getAbsolutePath(), "Open file", false);
        if (open) {
            try {
                Desktop.getDesktop().open(file);
            } catch (Exception error) {
                Dialogs.message(parent, "Could not open the file", "Open it from: " + file.getAbsolutePath(), Tone.INFO);
            }
        }
    }

    /** Saves a finished PDF document (receipt) chosen by the user. */
    static void savePdf(Component parent, String suggestedName, PdfWriter pdf) {
        File file = choose(parent, suggestedName, "pdf");
        if (file == null) {
            return;
        }
        Task.run(() -> {
            pdf.save(file.toPath());
            return file;
        }, saved -> done(parent, saved), error -> Dialogs.error(parent, error));
    }
}
